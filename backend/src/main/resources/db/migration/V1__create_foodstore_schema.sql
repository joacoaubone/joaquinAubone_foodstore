CREATE TABLE rol (
    codigo VARCHAR(20) PRIMARY KEY
);

CREATE TABLE estado_pedido (
    codigo VARCHAR(20) PRIMARY KEY,
    orden INTEGER,
    es_terminal BOOLEAN NOT NULL,
    CONSTRAINT ck_estado_pedido_orden CHECK (orden IS NULL OR orden > 0)
);

CREATE TABLE forma_pago (
    codigo VARCHAR(20) PRIMARY KEY,
    habilitada BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash CHAR(60) NOT NULL,
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_password_hash_bcrypt_strength_12
        CHECK (password_hash ~ '^\$2[aby]\$12\$[./A-Za-z0-9]{53}$')
);

CREATE TABLE usuario_rol (
    usuario_id BIGINT NOT NULL,
    rol_codigo VARCHAR(20) NOT NULL,
    CONSTRAINT pk_usuario_rol PRIMARY KEY (usuario_id, rol_codigo),
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (rol_codigo) REFERENCES rol (codigo)
);

CREATE TABLE intento_acceso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    exitoso BOOLEAN NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    precio NUMERIC(10, 2) NOT NULL,
    stock_cantidad INTEGER NOT NULL DEFAULT 0,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_producto_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) BETWEEN 1 AND 120),
    CONSTRAINT ck_producto_precio CHECK (precio > 0),
    CONSTRAINT ck_producto_stock CHECK (stock_cantidad >= 0)
);

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    estado_codigo VARCHAR(20) NOT NULL,
    direccion_entrega TEXT NOT NULL,
    total NUMERIC(10, 2) NOT NULL,
    expira_en TIMESTAMPTZ,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_pedido_estado FOREIGN KEY (estado_codigo) REFERENCES estado_pedido (codigo),
    CONSTRAINT ck_pedido_total CHECK (total >= 0),
    CONSTRAINT ck_pedido_expiracion CHECK (
        (estado_codigo = 'PENDIENTE' AND expira_en IS NOT NULL)
        OR (estado_codigo <> 'PENDIENTE' AND expira_en IS NULL)
    )
);

CREATE TABLE detalle_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_snapshot NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_detalle_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT fk_detalle_pedido_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT ck_detalle_pedido_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_pedido_precio CHECK (precio_snapshot > 0)
);

CREATE TABLE movimiento_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    cantidad INTEGER NOT NULL,
    pedido_id BIGINT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_movimiento_stock_producto FOREIGN KEY (producto_id) REFERENCES producto (id),
    CONSTRAINT fk_movimiento_stock_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT ck_movimiento_stock_tipo_cantidad CHECK (
        (tipo = 'ENTRADA' AND cantidad > 0)
        OR (tipo = 'SALIDA_VENTA' AND cantidad < 0)
        OR (tipo = 'REPOSICION_CANCELACION' AND cantidad > 0)
        OR (tipo = 'AJUSTE_MANUAL' AND cantidad <> 0)
    ),
    CONSTRAINT ck_movimiento_stock_tipo CHECK (
        tipo IN ('ENTRADA', 'SALIDA_VENTA', 'REPOSICION_CANCELACION', 'AJUSTE_MANUAL')
    )
);

CREATE TABLE historial_estado_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    estado_desde VARCHAR(20),
    estado_hacia VARCHAR(20) NOT NULL,
    actor_rol VARCHAR(20) NOT NULL,
    motivo TEXT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_historial_estado_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT ck_historial_estado_desde CHECK (
        estado_desde IS NULL
        OR estado_desde IN ('PENDIENTE', 'CONFIRMADO', 'EN_PREP', 'ENTREGADO', 'CANCELADO')
    ),
    CONSTRAINT ck_historial_estado_hacia CHECK (
        estado_hacia IN ('PENDIENTE', 'CONFIRMADO', 'EN_PREP', 'ENTREGADO', 'CANCELADO')
    ),
    CONSTRAINT ck_historial_motivo_cancelacion CHECK (
        estado_hacia <> 'CANCELADO' OR NULLIF(TRIM(motivo), '') IS NOT NULL
    )
);

CREATE TABLE pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    forma_pago_codigo VARCHAR(20) NOT NULL,
    monto NUMERIC(10, 2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    confirmado_en TIMESTAMPTZ,
    anulado_en TIMESTAMPTZ,
    CONSTRAINT uq_pago_pedido UNIQUE (pedido_id),
    CONSTRAINT fk_pago_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT fk_pago_forma_pago FOREIGN KEY (forma_pago_codigo) REFERENCES forma_pago (codigo),
    CONSTRAINT ck_pago_monto CHECK (monto >= 0),
    CONSTRAINT ck_pago_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'ANULADO')),
    CONSTRAINT ck_pago_fechas_estado CHECK (
        (estado = 'PENDIENTE' AND confirmado_en IS NULL AND anulado_en IS NULL)
        OR (estado = 'CONFIRMADO' AND confirmado_en IS NOT NULL AND anulado_en IS NULL)
        OR (estado = 'ANULADO' AND anulado_en IS NOT NULL)
    )
);

CREATE TABLE evento_salida (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo TEXT NOT NULL,
    canal TEXT NOT NULL,
    payload JSONB NOT NULL,
    publicado_en TIMESTAMPTZ,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE clave_idempotencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    clave UUID NOT NULL,
    huella CHAR(64) NOT NULL,
    estado VARCHAR(12) NOT NULL,
    pedido_id BIGINT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_clave_idempotencia_usuario_clave UNIQUE (usuario_id, clave),
    CONSTRAINT fk_clave_idempotencia_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_clave_idempotencia_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT ck_clave_idempotencia_huella CHECK (huella ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_clave_idempotencia_estado CHECK (estado IN ('EN_CURSO', 'COMPLETADA')),
    CONSTRAINT ck_clave_idempotencia_pedido CHECK (
        (estado = 'EN_CURSO' AND pedido_id IS NULL)
        OR (estado = 'COMPLETADA' AND pedido_id IS NOT NULL)
    )
);

CREATE INDEX idx_usuario_rol_rol_codigo ON usuario_rol (rol_codigo);
CREATE INDEX idx_intento_acceso_email_creado ON intento_acceso (email, creado_en DESC);
CREATE INDEX idx_pedido_usuario_creado ON pedido (usuario_id, creado_en DESC);
CREATE INDEX idx_pedido_estado ON pedido (estado_codigo);
CREATE INDEX idx_pedido_pendiente_expira ON pedido (expira_en)
    WHERE estado_codigo = 'PENDIENTE' AND expira_en IS NOT NULL;
CREATE INDEX idx_detalle_pedido_pedido ON detalle_pedido (pedido_id);
CREATE INDEX idx_detalle_pedido_producto ON detalle_pedido (producto_id);
CREATE INDEX idx_movimiento_stock_producto_creado ON movimiento_stock (producto_id, creado_en DESC);
CREATE INDEX idx_movimiento_stock_pedido ON movimiento_stock (pedido_id);
CREATE INDEX idx_historial_estado_pedido_creado ON historial_estado_pedido (pedido_id, creado_en);
CREATE INDEX idx_pago_forma_pago ON pago (forma_pago_codigo);
CREATE INDEX idx_evento_salida_pendiente ON evento_salida (id) WHERE publicado_en IS NULL;
CREATE INDEX idx_clave_idempotencia_pedido ON clave_idempotencia (pedido_id);
